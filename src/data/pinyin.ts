const TONE_MAP: Record<string, string> = {
  ā: "a", á: "a", ǎ: "a", à: "a",
  ē: "e", é: "e", ě: "e", è: "e",
  ī: "i", í: "i", ǐ: "i", ì: "i",
  ō: "o", ó: "o", ǒ: "o", ò: "o",
  ū: "u", ú: "u", ǔ: "u", ù: "u",
  ǖ: "v", ǘ: "v", ǚ: "v", ǜ: "v", ü: "v",
  ń: "n", ň: "n", ǹ: "n", ḿ: "m",
};

/** 去声调（并把 ü 统一写成 v），用于判断两个字"听起来是不是一样的" */
export function syllableOf(py: string): string {
  let out = "";
  for (const ch of py.toLowerCase()) out += TONE_MAP[ch] ?? ch;
  return out.replace(/\s+/g, "");
}

export function sameSound(a: string, b: string): boolean {
  return syllableOf(a) === syllableOf(b);
}
